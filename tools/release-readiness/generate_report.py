#!/usr/bin/env python3
"""
Apple Native Engineer — Release Readiness Report Generator
Consolidates project inspection, privacy manifest compliance, metadata validation,
and asset checks into a unified App Store release readiness report.
"""

import sys
import os
import json
import argparse
from datetime import datetime, timezone
from pathlib import Path

# Add tools to sys.path
TOOLS_DIR = Path(__file__).parent.parent
sys.path.insert(0, str(TOOLS_DIR / "project-inspector"))
sys.path.insert(0, str(TOOLS_DIR / "privacy-auditor"))
sys.path.insert(0, str(TOOLS_DIR / "metadata-validator"))
sys.path.insert(0, str(TOOLS_DIR / "asset-validator"))

from inspect_project import inspect_project
from audit_privacy import run_privacy_audit
from validate_metadata import validate_metadata_file
from validate_assets import validate_app_icon

def evaluate_release_readiness(
    project_dir: str,
    metadata_file: str = None,
    icon_file: str = None
) -> dict:
    root = Path(project_dir).resolve()
    date_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    # 1. Project Inspection
    project_data = inspect_project(str(root))

    # 2. Privacy Audit
    privacy_data = run_privacy_audit(str(root))

    # 3. Metadata Validation
    metadata_data = None
    if metadata_file and Path(metadata_file).exists():
        metadata_data = validate_metadata_file(metadata_file)
    else:
        # Search for metadata in templates or project
        meta_candidates = list(root.glob("**/app_metadata*.json"))
        if meta_candidates:
            metadata_data = validate_metadata_file(str(meta_candidates[0]))

    # 4. Icon Validation
    icon_data = None
    if icon_file and Path(icon_file).exists():
        icon_data = validate_app_icon(icon_file)
    else:
        icon_candidates = list(root.glob("**/AppIcon*.png"))
        if icon_candidates:
            icon_data = validate_app_icon(str(icon_candidates[0]))

    # Calculate Score
    score = 100
    critical_issues = []
    warnings = []

    # Privacy score
    if not privacy_data.get("compliant", True):
        score -= 35
        critical_issues.extend(privacy_data.get("critical_issues", []))
    warnings.extend(privacy_data.get("warnings", []))

    # Metadata score
    if metadata_data:
        if not metadata_data.get("overall_valid", True):
            score -= 25
            critical_issues.append("App Store metadata contains critical validation errors.")
    else:
        score -= 10
        warnings.append("No metadata file provided for review.")

    # Icon score
    if icon_data:
        if not icon_data.get("valid", True):
            score -= 20
            critical_issues.extend(icon_data.get("errors", []))
    else:
        warnings.append("No 1024x1024 App Store icon file provided for review.")

    score = max(0, score)
    status = "READY FOR SUBMISSION" if score >= 90 and not critical_issues else ("ACTION REQUIRED" if score >= 60 else "BLOCKED")

    return {
        "timestamp": date_str,
        "project_directory": str(root),
        "readiness_status": status,
        "score": score,
        "critical_issues": critical_issues,
        "warnings": warnings,
        "project_summary": project_data,
        "privacy_audit": privacy_data,
        "metadata_validation": metadata_data,
        "icon_validation": icon_data
    }

def format_markdown_report(report: dict) -> str:
    proj = report["project_summary"]
    lines = [
        "# App Store Release Readiness Report",
        "",
        f"**Generated by**: Apple Native Engineer Toolkit  ",
        f"**Directory**: `{report['project_directory']}`  ",
        f"**Timestamp**: {report['timestamp']}  ",
        f"**Readiness Status**: **{report['readiness_status']}**  ",
        f"**Release Readiness Score**: **{report['score']}/100**",
        "",
        "---",
        "",
        "## Executive Summary",
        f"- **Project Type**: {proj['project_type']}",
        f"- **Swift Files**: {proj['swift_files_count']}",
        f"- **Frameworks Detected**: {', '.join(proj['frameworks_detected']) or 'None'}",
        f"- **Privacy Manifest**: {'[FOUND]' if proj['privacy_manifest_found'] else '[MISSING]'}",
        "",
        "---",
        "",
        "## Quality Gate Breakdown",
        "",
        "| Gate | Status | Findings |",
        "| :--- | :--- | :--- |",
        f"| **Privacy Manifest (`PrivacyInfo.xcprivacy`)** | {'PASS' if report['privacy_audit']['compliant'] else 'FAIL'} | {len(report['privacy_audit']['critical_issues'])} critical issue(s) |",
        f"| **Store Metadata** | {'PASS' if (report['metadata_validation'] and report['metadata_validation']['overall_valid']) else ('FAIL' if report['metadata_validation'] else 'NOT INSPECTED')} | {'Valid' if report['metadata_validation'] and report['metadata_validation']['overall_valid'] else 'Check metadata file'} |",
        f"| **App Icon (1024x1024, No Alpha)** | {'PASS' if (report['icon_validation'] and report['icon_validation']['valid']) else ('FAIL' if report['icon_validation'] else 'NOT INSPECTED')} | {'Valid' if report['icon_validation'] and report['icon_validation']['valid'] else 'Inspect icon asset'} |",
        ""
    ]

    if report["critical_issues"]:
        lines.append("## Critical App Store Review Risks")
        for iss in report["critical_issues"]:
            lines.append(f"- 🔴 **{iss}**")
        lines.append("")

    if report["warnings"]:
        lines.append("## Warnings & Optimization Suggestions")
        for w in report["warnings"]:
            lines.append(f"- ⚠️ {w}")
        lines.append("")

    lines.append("---")
    lines.append("*Report generated automatically by Apple Native Engineer (Open-Source Toolkit).*")
    return "\n".join(lines)

def main():
    parser = argparse.ArgumentParser(description="Apple Native Engineer — Release Readiness Generator")
    parser.add_argument("path", nargs="?", default=".", help="Path to project directory")
    parser.add_argument("--metadata", type=str, help="Path to metadata JSON file")
    parser.add_argument("--icon", type=str, help="Path to 1024x1024 icon file")
    parser.add_argument("--json", action="store_true", help="Output machine-readable JSON")
    parser.add_argument("--output", type=str, help="Save report to specified markdown file path")
    args = parser.parse_args()

    try:
        report = evaluate_release_readiness(args.path, metadata_file=args.metadata, icon_file=args.icon)
        md = format_markdown_report(report)

        if args.output:
            out_path = Path(args.output).resolve()
            out_path.write_text(md, encoding="utf-8")
            print(f"✓ Release report written to {out_path}")

        if args.json:
            print(json.dumps(report, indent=2))
        elif not args.output:
            print(md)

        sys.exit(0 if report["score"] >= 60 and not report["critical_issues"] else 1)
    except Exception as e:
        print(f"Failed to generate release readiness report: {e}", file=sys.stderr)
        sys.exit(1)

if __name__ == "__main__":
    main()
